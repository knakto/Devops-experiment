find . -maxdepth 1 -mindepth 1 \( -type f -o -type d \) ! -name '.*' | wc -l | tr -d ' '










# find .	ค้นหาเริ่มจากโฟลเดอร์ปัจจุบัน (.)
# -maxdepth 1	ค้นแค่ชั้นแรก ไม่ลงไปในโฟลเดอร์ย่อย
# -mindepth 1	ไม่นับตัว . (โฟลเดอร์ปัจจุบันเอง)
# \( -type f -o -type d \)	เอาเฉพาะไฟล์ (f) หรือ (-o) โฟลเดอร์ (d) ส่วน \( \) คือวงเล็บจัดกลุ่มเงื่อนไข ต้องใส่ \ เพื่อไม่ให้ shell ตีความเอง
# ! -name '.*'	ไม่เอาชื่อที่ขึ้นต้นด้วยจุด เช่น .git, .env, .DS_Store (ไฟล์ซ่อน)
# | wc -l	ส่งผลลัพธ์ไปนับจำนวนบรรทัด (1 บรรทัด = 1 รายการ)
# | tr -d ' '	ลบช่องว่างออก เพราะ wc บน macOS จะเติมช่องว่างนำหน้าตัวเลข เช่น 42 ให้เหลือ 42












